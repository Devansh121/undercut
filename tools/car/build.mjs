// Rebuilds every car asset from nothing: three GLB levels of detail, the livery masks and the
// livery index. Blender runs headless from the tarball under ~/.cache/undercut/blender (fetched
// and checksum-verified on first use). Output is deterministic; assets/MANIFEST.json records
// the sha256 of every file.
//
//   npm run car:build             build into apps/web/public/assets/car and update the manifest
//   npm run car:build -- --check  build into a temporary directory and compare with the manifest
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const ASSET_DIR = 'apps/web/public/assets/car';
const LODS = ['high', 'mobile', 'far'];
// Triangle budgets per level of detail (docs/adr/0005-car-model.md); the build fails above them.
const TRIANGLE_BUDGET = { high: 120000, mobile: 40000, far: 12000 };
const BLENDER_VERSION = '5.2.4';
const BLENDER_DIR = path.join(os.homedir(), '.cache/undercut/blender');
const BLENDER_NAME = `blender-${BLENDER_VERSION}-linux-x64`;
const BLENDER_URL = `https://download.blender.org/release/Blender5.2/${BLENDER_NAME}.tar.xz`;
const SHA_URL = `https://download.blender.org/release/Blender5.2/blender-${BLENDER_VERSION}.sha256`;

const check = process.argv.includes('--check');

function blender() {
  const bin = path.join(BLENDER_DIR, BLENDER_NAME, 'blender');
  if (fs.existsSync(bin)) return bin;
  if (process.platform !== 'linux' || process.arch !== 'x64') {
    throw new Error(
      `Blender ${BLENDER_VERSION} is fetched for linux-x64 only; install it at ${bin}`,
    );
  }
  fs.mkdirSync(BLENDER_DIR, { recursive: true });
  const tar = path.join(BLENDER_DIR, `${BLENDER_NAME}.tar.xz`);
  const sums = path.join(BLENDER_DIR, `blender-${BLENDER_VERSION}.sha256`);
  console.log(`Fetching ${BLENDER_URL}`);
  execFileSync('curl', ['-fL', '-o', tar, BLENDER_URL], { stdio: 'inherit' });
  execFileSync('curl', ['-fL', '-o', sums, SHA_URL], { stdio: 'inherit' });
  const want = fs
    .readFileSync(sums, 'utf8')
    .split('\n')
    .find((l) => l.includes(`${BLENDER_NAME}.tar.xz`))
    ?.split(/\s+/)[0];
  const got = crypto.createHash('sha256').update(fs.readFileSync(tar)).digest('hex');
  if (!want || want !== got) throw new Error(`Blender tarball checksum mismatch: ${got}`);
  execFileSync('tar', ['xf', tar, '-C', BLENDER_DIR], { stdio: 'inherit' });
  fs.rmSync(tar);
  return bin;
}

function run(bin, args) {
  const out = execFileSync(
    bin,
    [
      '-b',
      '--factory-startup',
      '-noaudio',
      '--python-exit-code',
      '1',
      '-P',
      path.join(here, 'car.py'),
      '--',
      ...args,
    ],
    { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  );
  const lines = out.split('\n').filter((l) => /^(EXPORTED|MASKS|STATS)/.test(l));
  for (const l of lines) console.log(`  ${l}`);
  if (/Traceback|Error:/.test(out)) {
    console.error(out);
    throw new Error('Blender reported an error');
  }
}

function sha256(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

function* walk(dir) {
  for (const e of fs
    .readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) yield* walk(full);
    else yield full;
  }
}

/** Livery index for the renderer: which mask each team uses, and its colours. */
function liveryIndex() {
  const teams = JSON.parse(fs.readFileSync(path.join(root, 'design/teams.json'), 'utf8')).teams;
  return {
    $comment:
      'Generated by tools/car/build.mjs from design/teams.json. One mask per team, drawn from its design in tools/car/carlib/livery.py. Masks: R secondary weight, G accent weight, B bare carbon; primary is the rest. See docs/car-asset.md.',
    atlasSize: 1024,
    teams: Object.fromEntries(
      teams.map((t) => [
        t.id,
        {
          mask: `livery/${t.id}.png`,
          pattern: t.liveryPattern,
          primary: t.colours.primary,
          secondary: t.colours.secondary,
          accent: t.colours.accent,
        },
      ]),
    ),
  };
}

function build(outDir, statsDir) {
  const bin = blender();
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  for (const lod of LODS) {
    console.log(`Building ${lod}`);
    run(bin, ['--mode', 'export', '--lod', lod, '--out', outDir, '--stats-dir', statsDir]);
    const { triangles } = glbStats(path.join(outDir, `car_${lod}.glb`));
    if (triangles > TRIANGLE_BUDGET[lod])
      throw new Error(
        `car_${lod}.glb has ${triangles} triangles, over its ${TRIANGLE_BUDGET[lod]} budget`,
      );
  }
  console.log('Drawing livery masks');
  run(bin, ['--mode', 'masks', '--out', outDir]);
  fs.writeFileSync(
    path.join(outDir, 'livery/index.json'),
    `${JSON.stringify(liveryIndex(), null, 2)}\n`,
  );
}

/**
 * Triangles, draw calls (primitives) and nodes counted from a GLB as shipped: what the
 * renderer will draw, not what the generator built before export.
 */
function glbStats(file) {
  const buf = fs.readFileSync(file);
  const json = JSON.parse(buf.subarray(20, 20 + buf.readUInt32LE(12)).toString('utf8'));
  const nodes = {};
  let triangles = 0;
  let primitives = 0;
  const walkNode = (i) => {
    const n = json.nodes[i];
    if (n.mesh !== undefined) {
      const prims = json.meshes[n.mesh].primitives;
      const tris = prims.reduce((t, p) => t + json.accessors[p.indices].count / 3, 0);
      nodes[n.name] = {
        triangles: tris,
        primitives: prims.length,
        materials: prims.map((p) => json.materials[p.material].name),
        morph_targets: prims[0].targets ? prims[0].targets.length : 0,
      };
      triangles += tris;
      primitives += prims.length;
    }
    for (const c of n.children ?? []) walkNode(c);
  };
  for (const i of json.scenes[json.scene ?? 0].nodes) walkNode(i);
  const images = (json.images ?? []).map((im) => ({
    name: im.name,
    mimeType: im.mimeType,
    bytes: json.bufferViews[im.bufferView].byteLength,
  }));
  return {
    file: path.basename(file),
    bytes: buf.length,
    triangles,
    draw_calls: primitives,
    nodes,
    images,
  };
}

const CHANGES = {
  '.glb':
    'Generated by tools/car (npm run car:build): bodywork, wings, wheels and suspension lofted by script in Blender 5.2, procedural textures, Draco-compressed glTF',
  '.png': 'Generated by tools/car (npm run car:build): livery mask drawn from the pattern code',
  '.json': 'Generated by tools/car/build.mjs from design/teams.json',
};

function manifestEntries(dir, relBase) {
  return [...walk(dir)].map((full) => {
    const rel = path.join(relBase, path.relative(dir, full)).split(path.sep).join('/');
    return {
      file: rel,
      source_url: 'tools/car/build.mjs (this repository)',
      author: 'Project contributors',
      licence: 'MIT',
      changes: CHANGES[path.extname(full)] ?? 'Generated by tools/car',
      sha256: sha256(full),
    };
  });
}

const manifestPath = path.join(root, 'assets/MANIFEST.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

if (check) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'car-check-'));
  try {
    build(tmp, path.join(tmp, '.stats'));
    fs.rmSync(path.join(tmp, '.stats'), { recursive: true, force: true });
    const fresh = manifestEntries(tmp, ASSET_DIR);
    const recorded = new Map(
      manifest.filter((e) => e.file.startsWith(`${ASSET_DIR}/`)).map((e) => [e.file, e.sha256]),
    );
    let bad = 0;
    for (const e of fresh) {
      const ok = recorded.get(e.file) === e.sha256;
      if (!ok) bad += 1;
      console.log(`${ok ? 'ok  ' : 'DIFF'} ${e.file} ${e.sha256}`);
      recorded.delete(e.file);
    }
    for (const f of recorded.keys()) {
      bad += 1;
      console.log(`GONE ${f}`);
    }
    if (bad) {
      console.error(`${bad} car asset(s) differ from assets/MANIFEST.json`);
      process.exitCode = 1;
    } else console.log('Rebuilt car assets match assets/MANIFEST.json');
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
} else {
  const out = path.join(root, ASSET_DIR);
  const statsDir = path.join(root, 'docs/evidence/m2-car/stats');
  build(out, statsDir);
  const kept = manifest.filter((e) => !e.file.startsWith(`${ASSET_DIR}/`));
  const entries = manifestEntries(out, ASSET_DIR);
  fs.writeFileSync(manifestPath, `${JSON.stringify([...kept, ...entries], null, 2)}\n`);
  // one stats.json for the evidence folder, measured on the shipped files
  const stats = Object.fromEntries(
    LODS.map((lod) => {
      const blender = JSON.parse(fs.readFileSync(path.join(statsDir, `stats_${lod}.json`), 'utf8'));
      return [lod, { ...glbStats(path.join(out, `car_${lod}.glb`)), textures: blender.images }];
    }),
  );
  stats.masks = Object.fromEntries(
    [...walk(path.join(out, 'livery'))].map((f) => [
      path.basename(f),
      { bytes: fs.statSync(f).size },
    ]),
  );
  stats.total_bytes = [...walk(out)].reduce((n, f) => n + fs.statSync(f).size, 0);
  fs.writeFileSync(
    path.join(root, 'docs/evidence/m2-car/stats.json'),
    `${JSON.stringify(stats, null, 2)}\n`,
  );
  fs.rmSync(statsDir, { recursive: true, force: true });
  console.log(
    `Wrote ${entries.length} files (${stats.total_bytes} bytes) and updated the manifest`,
  );
}
