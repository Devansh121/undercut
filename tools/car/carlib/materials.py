"""Materials. Principled BSDF only, wired so the glTF exporter writes metallic-roughness,
clearcoat, normal, occlusion and emissive. Textures are generated by textures.py; nothing here
depends on a Blender-only shader node that would not survive export."""

import bpy

from .textures import CARBON_TILE_M

CARBON_SCALE = 1.0 / CARBON_TILE_M


def srgb(hexstr):
    h = hexstr.lstrip("#")
    out = []
    for i in (0, 2, 4):
        c = int(h[i:i + 2], 16) / 255.0
        out.append(c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4)
    return (*out, 1.0)


def _new(name):
    m = bpy.data.materials.new(name)
    try:
        m.use_nodes = True
    except Exception:
        pass
    m.use_backface_culling = True
    nt = m.node_tree
    b = next(n for n in nt.nodes if n.type == "BSDF_PRINCIPLED")
    return m, nt, b


def _tex(nt, image, uv_name, non_color=False, scale=None):
    t = nt.nodes.new("ShaderNodeTexImage")
    t.image = image
    t.interpolation = "Linear"
    uv = nt.nodes.new("ShaderNodeUVMap")
    uv.uv_map = uv_name
    if scale is not None:
        mp = nt.nodes.new("ShaderNodeMapping")
        mp.vector_type = "POINT"
        mp.inputs["Scale"].default_value = (scale, scale, 1.0)
        nt.links.new(uv.outputs["UV"], mp.inputs["Vector"])
        nt.links.new(mp.outputs["Vector"], t.inputs["Vector"])
    else:
        nt.links.new(uv.outputs["UV"], t.inputs["Vector"])
    return t


def _normal(nt, b, tex, strength=1.0, uv="UVMetric"):
    nm = nt.nodes.new("ShaderNodeNormalMap")
    nm.uv_map = uv
    nm.inputs["Strength"].default_value = strength
    nt.links.new(tex.outputs["Color"], nm.inputs["Color"])
    nt.links.new(nm.outputs["Normal"], b.inputs["Normal"])
    return nm


def build(textures, base_colour="#8C9096", livery=None):
    """textures: dict from textures.py (Blender images) or {} for untextured review builds.
    Returns name -> material for every material name the geometry uses."""
    T = textures
    mats = {}

    def principled(name, rgba, rough, metal=0.0, coat=0.0, coat_rough=0.03, double=False):
        m, nt, b = _new(name)
        b.inputs["Base Color"].default_value = rgba
        b.inputs["Roughness"].default_value = rough
        b.inputs["Metallic"].default_value = metal
        b.inputs["Coat Weight"].default_value = coat
        b.inputs["Coat Roughness"].default_value = coat_rough
        m.diffuse_color = rgba
        m.use_backface_culling = not double
        mats[name] = m
        return m, nt, b

    # painted bodywork: the renderer recolours it from the livery mask on UV0; the exported
    # base colour is a neutral primer so the file reads as unpainted without the mask
    m, nt, b = principled("paint", srgb(base_colour), 0.30, coat=1.0, coat_rough=0.04)
    if livery is not None:
        _livery_nodes(nt, b, *livery)
    if "body_detail" in T:
        # panel gaps, fasteners and louvres, drawn in the livery atlas (UV0)
        t = _tex(nt, T["body_detail"], "UVMap", non_color=True)
        _normal(nt, b, t, 1.0, uv="UVMap")
    mats["paint_edge"] = m

    # carbon: rougher with a softer clear coat and a stronger weave relief, so broad highlights
    # break up instead of reading as polished metal
    m, nt, b = principled("carbon", srgb("#101114"), 0.55, coat=0.45, coat_rough=0.30)
    if "carbon_normal" in T:
        t = _tex(nt, T["carbon_normal"], "UVMetric", non_color=True, scale=CARBON_SCALE)
        _normal(nt, b, t, 0.9)
    if "carbon_base" in T:
        t = _tex(nt, T["carbon_base"], "UVMetric", scale=CARBON_SCALE)
        nt.links.new(t.outputs["Color"], b.inputs["Base Color"])
    m, nt, b = principled("carbon_matte", srgb("#0B0C0D"), 0.66, coat=0.0)
    if "carbon_normal" in T:
        t = _tex(nt, T["carbon_normal"], "UVMetric", non_color=True, scale=CARBON_SCALE)
        _normal(nt, b, t, 0.6)
    principled("dark", srgb("#0B0C0D"), 0.75, double=True)
    principled("interior", srgb("#18191B"), 0.85, double=True)
    principled("headrest", srgb("#1E1F22"), 0.80)
    principled("plank", srgb("#2A2219"), 0.70)
    principled("metal_satin", srgb("#8E9296"), 0.38, metal=1.0)
    principled("metal_dark", srgb("#3A3D41"), 0.45, metal=1.0)
    principled("exhaust", srgb("#7B6A5A"), 0.42, metal=1.0)
    principled("soot", srgb("#0A0A0A"), 0.9)
    m, nt, b = principled("tyre", srgb("#FFFFFF"), 0.90)
    m.diffuse_color = srgb("#1A1A1B")  # viewport and Workbench sheets only
    if "tyre_normal" in T:
        t = _tex(nt, T["tyre_normal"], "UVMetric", non_color=True)
        _normal(nt, b, t, 1.0)
    if "tyre_base" in T:
        t = _tex(nt, T["tyre_base"], "UVMetric")
        nt.links.new(t.outputs["Color"], b.inputs["Base Color"])
    principled("rim", srgb("#1F2124"), 0.34, metal=1.0)
    m, nt, b = principled("wheel_cover", srgb("#16171A"), 0.40, coat=0.6, coat_rough=0.2)
    if "carbon_normal" in T:
        t = _tex(nt, T["carbon_normal"], "UVMetric", non_color=True, scale=CARBON_SCALE)
        _normal(nt, b, t, 0.5)
    principled("nut", srgb("#B8BCC0"), 0.30, metal=1.0)
    m, nt, b = principled("brake_disc", srgb("#2C2B2A"), 0.62)
    b.inputs["Emission Color"].default_value = srgb("#FF6A1A")
    # strength 1 keeps the glow ramp in the file; the renderer drives emissiveIntensity (0 = cold)
    b.inputs["Emission Strength"].default_value = 1.0
    if "disc_glow" in T:
        t = _tex(nt, T["disc_glow"], "UVMetric")
        nt.links.new(t.outputs["Color"], b.inputs["Emission Color"])
    principled("caliper", srgb("#2E3136"), 0.4, metal=0.6)
    principled("helmet", srgb("#E8E6E1"), 0.22, coat=1.0, coat_rough=0.02)
    principled("visor", srgb("#0E1014"), 0.05, metal=0.6, coat=1.0, coat_rough=0.0)
    m, nt, b = principled("display", srgb("#05070A"), 0.2)
    b.inputs["Emission Color"].default_value = srgb("#1C2A33")
    b.inputs["Emission Strength"].default_value = 1.0
    principled("grip", srgb("#1A1A1B"), 0.9)
    principled("mirror_glass", srgb("#C8CCD0"), 0.02, metal=1.0)
    principled("tcam", srgb("#101112"), 0.5)
    principled("boot", srgb("#121212"), 0.8)
    m, nt, b = principled("decal", (1.0, 1.0, 1.0, 1.0), 0.32, coat=1.0)
    b.inputs["Alpha"].default_value = 0.0
    try:
        m.surface_render_method = "BLENDED"
    except Exception:
        pass
    m, nt, b = principled("rain_light", srgb("#300808"), 0.4)
    b.inputs["Emission Color"].default_value = srgb("#FF1A10")
    b.inputs["Emission Strength"].default_value = 0.0
    return mats


def _occlusion(nt, tex):
    """The glTF exporter reads occlusion from a custom node group named 'glTF Material Output'."""
    grp = bpy.data.node_groups.get("glTF Material Output")
    if grp is None:
        grp = bpy.data.node_groups.new("glTF Material Output", "ShaderNodeTree")
        grp.interface.new_socket("Occlusion", in_out="INPUT", socket_type="NodeSocketFloat")
    node = nt.nodes.new("ShaderNodeGroup")
    node.node_tree = grp
    sep = nt.nodes.new("ShaderNodeSeparateColor")
    nt.links.new(tex.outputs["Color"], sep.inputs["Color"])
    nt.links.new(sep.outputs["Red"], node.inputs["Occlusion"])


def _livery_nodes(nt, b, mask_image, primary, secondary, accent):
    """Review renders only: mix the team colours from the mask the way the game shader does."""
    t = _tex(nt, mask_image, "UVMap", non_color=True)
    t.interpolation = "Linear"
    sep = nt.nodes.new("ShaderNodeSeparateColor")
    nt.links.new(t.outputs["Color"], sep.inputs["Color"])
    m1 = nt.nodes.new("ShaderNodeMix")
    m1.data_type = "RGBA"
    m1.inputs[6].default_value = srgb(primary)
    m1.inputs[7].default_value = srgb(secondary)
    nt.links.new(sep.outputs["Red"], m1.inputs[0])
    m2 = nt.nodes.new("ShaderNodeMix")
    m2.data_type = "RGBA"
    nt.links.new(m1.outputs[2], m2.inputs[6])
    m2.inputs[7].default_value = srgb(accent)
    nt.links.new(sep.outputs["Green"], m2.inputs[0])
    m3 = nt.nodes.new("ShaderNodeMix")
    m3.data_type = "RGBA"
    nt.links.new(m2.outputs[2], m3.inputs[6])
    m3.inputs[7].default_value = srgb("#141518")
    nt.links.new(sep.outputs["Blue"], m3.inputs[0])
    nt.links.new(m3.outputs[2], b.inputs["Base Color"])
    rough = nt.nodes.new("ShaderNodeMapRange")
    nt.links.new(sep.outputs["Blue"], rough.inputs["Value"])
    rough.inputs["To Min"].default_value = 0.30
    rough.inputs["To Max"].default_value = 0.38
    nt.links.new(rough.outputs["Result"], b.inputs["Roughness"])
